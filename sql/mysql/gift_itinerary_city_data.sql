CREATE TEMPORARY TABLE tmp_itinerary_city_heat_score AS
SELECT city.city_id,
       COALESCE(city_rank.hot, 0) AS hot,
       ROW_NUMBER() OVER (
         PARTITION BY city.province_id
         ORDER BY COALESCE(city_rank.heat_rank, 1000), city.city_id
       ) AS city_sort
FROM gift_itinerary_city AS city
LEFT JOIN tmp_itinerary_city_heat_rank AS city_rank
  ON city_rank.city_id = city.city_id;

UPDATE gift_itinerary_city AS city
JOIN tmp_itinerary_province_heat_rank AS province_rank
  ON province_rank.province_id = city.province_id
JOIN tmp_itinerary_city_heat_score AS city_score
  ON city_score.city_id = city.city_id
SET city.hot = city_score.hot,
    city.sort = province_rank.heat_rank * 1000 + city_score.city_sort;

