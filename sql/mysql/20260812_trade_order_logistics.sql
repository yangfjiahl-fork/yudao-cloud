  UNIQUE KEY `uk_tenant_order_id` (`tenant_id`, `order_id`),
  UNIQUE KEY `uk_tenant_cache_key` (`tenant_id`, `cache_key`)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci COMMENT='订单物流表';
