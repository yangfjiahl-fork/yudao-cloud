  `order_id` bigint NOT NULL COMMENT '订单编号',
  `logistics_id` bigint NOT NULL COMMENT '物流公司编号',
  `express_code` varchar(32) CHARACTER SET utf8mb4 COLLATE utf8mb4_unicode_ci NOT NULL COMMENT '物流公司编码',
  `logistics_no` varchar(64) CHARACTER SET utf8mb4 COLLATE utf8mb4_unicode_ci NOT NULL COMMENT '物流单号',
  `cache_key` char(64) CHARACTER SET utf8mb4 COLLATE utf8mb4_unicode_ci NOT NULL COMMENT '缓存及回调关联键',
  `provider` varchar(32) CHARACTER SET utf8mb4 COLLATE utf8mb4_unicode_ci NOT NULL COMMENT '查询服务商',
  `subscribe_status` tinyint NOT NULL DEFAULT 0 COMMENT '订阅状态：0 待提交，10 成功，20 失败',
  `subscribe_message` varchar(512) CHARACTER SET utf8mb4 COLLATE utf8mb4_unicode_ci NULL COMMENT '订阅结果信息',
